//! Build-time code generation.
//!
//! The colorls gem ships its icon/color tables as YAML and parses them at
//! startup. We instead parse the vendored copies here, at build time, and emit
//! static `phf` maps so the binary pays *zero* YAML-parsing cost on startup.
//! User overrides in `~/.config/colorls/*.yaml` are still honored at runtime
//! (see `src/config.rs`), matching the gem's behavior.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// Parse a flat `key: value` YAML map (the only shape colorls data uses).
///
/// Handles `# comments`, blank lines, optional surrounding quotes, and keys
/// that contain dots (e.g. `gruntfile.js`). Returns pairs in file order.
fn parse_flat_yaml(src: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for raw in src.lines() {
        let line = raw.trim_end();
        let trimmed = line.trim_start();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some(colon) = line.find(':') else { continue };
        let key = line[..colon].trim().trim_matches(|c| c == '"' || c == '\'');
        let mut val = line[colon + 1..].trim().to_string();
        // Strip trailing inline comments only when the value is unquoted.
        if !val.starts_with('"') && !val.starts_with('\'')
            && let Some(h) = val.find(" #") {
                val = val[..h].trim_end().to_string();
            }
        let val = val.trim().trim_matches(|c| c == '"' || c == '\'').to_string();
        out.push((key.to_string(), val));
    }
    out
}

fn emit_str_map(out: &mut String, name: &str, pairs: &[(String, String)]) {
    writeln!(
        out,
        "pub static {name}: phf::Map<&'static str, &'static str> = "
    )
    .unwrap();
    let mut builder = phf_codegen::Map::new();
    // phf rejects duplicate keys; keep the first occurrence like a YAML load.
    let mut seen = std::collections::HashSet::new();
    let mut escaped: Vec<(String, String)> = Vec::new();
    for (k, v) in pairs {
        if seen.insert(k.clone()) {
            escaped.push((k.clone(), format!("{v:?}")));
        }
    }
    for (k, v) in &escaped {
        builder.entry(k.as_str(), v.as_str());
    }
    out.push_str(&builder.build().to_string());
    out.push_str(";\n\n");
}

fn main() {
    let data = Path::new(env!("CARGO_MANIFEST_DIR")).join("data");
    let read = |f: &str| fs::read_to_string(data.join(f)).unwrap_or_else(|e| panic!("read {f}: {e}"));

    let mut out = String::new();
    out.push_str("// @generated by build.rs from data/*.yaml and data/colors_x11.tsv\n\n");

    emit_str_map(&mut out, "FILES", &parse_flat_yaml(&read("files.yaml")));
    emit_str_map(&mut out, "FOLDERS", &parse_flat_yaml(&read("folders.yaml")));
    emit_str_map(
        &mut out,
        "FILE_ALIASES",
        &parse_flat_yaml(&read("file_aliases.yaml")),
    );
    emit_str_map(
        &mut out,
        "FOLDER_ALIASES",
        &parse_flat_yaml(&read("folder_aliases.yaml")),
    );
    emit_str_map(
        &mut out,
        "DARK_COLORS",
        &parse_flat_yaml(&read("dark_colors.yaml")),
    );
    emit_str_map(
        &mut out,
        "LIGHT_COLORS",
        &parse_flat_yaml(&read("light_colors.yaml")),
    );

    // Color-name -> SGR parameter body (e.g. "38;5;39" or "33"), captured
    // directly from Rainbow so our escapes are byte-identical to the gem.
    let tsv = read("colors_x11.tsv");
    let mut color_pairs: Vec<(String, String)> = Vec::new();
    for line in tsv.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let mut it = line.splitn(2, '\t');
        let (Some(name), Some(code)) = (it.next(), it.next()) else {
            continue;
        };
        color_pairs.push((name.trim().to_string(), code.trim().to_string()));
    }
    // "default" (reset-to-default fg) is a base Rainbow name absent from X11.
    if !color_pairs.iter().any(|(k, _)| k == "default") {
        color_pairs.push(("default".to_string(), "39".to_string()));
    }
    emit_str_map(&mut out, "X11_COLORS", &color_pairs);

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("generated.rs");
    fs::write(&dest, out).unwrap();

    println!("cargo:rerun-if-changed=data");
    for f in [
        "files.yaml",
        "folders.yaml",
        "file_aliases.yaml",
        "folder_aliases.yaml",
        "dark_colors.yaml",
        "light_colors.yaml",
        "colors_x11.tsv",
    ] {
        println!("cargo:rerun-if-changed=data/{f}");
    }
}
